def selfcheck():
    facts={'n':3};code='def solve(facts): return {"count":facts["n"]}\ndef check(answer,facts): return answer["count"]==sum(1 for _ in range(facts["n"]))'
    assert compact_audit({'refs':['n'],'code':code},facts)
    assert execute_compact(code,facts)['answer']=={'count':3}
    assert execute_compact(code,{'n':7})['answer']=={'count':7}
    for bad in [{'refs':[],'code':code},{'refs':['n','n'],'code':code},{'refs':['n'],'code':'def solve(facts): return {"count":3}\ndef check(answer,facts): return True'}]:
        try:compact_audit(bad,facts)
        except Exception:pass
        else:raise AssertionError('Bad refs/checker accepted')
    assert not execute_compact('import os\n'+code,facts)['pass']
    assert not execute_compact('def solve(facts): return {"count":1}\ndef check(answer,facts): return answer["count"]==facts["n"]',facts)['pass']
    assert min(range(3),key=lambda i:cascade_scores([1,20,100],[.9,.9,.9])[i])==0
    assert min(range(3),key=lambda i:cascade_scores([1,20,100],[0,1,1])[i])==1
    assert final_action('accept',False,0)=='escalate'
    assert final_action('accept',False,2)=='stop'
    tasks=build_tasks();assert len(tasks)==12 and len({x['id'] for x in tasks})==12
    original=B.build_tasks()
    assert all(t['prompt']!=x['prompt'] for t in tasks for x in original)
    a=Optimizer()
    for t in tasks:
        _,p=a.prepare(t,'compact' if t['family'] in PROGRAM_FAMILIES else 'direct')
        assert p['selected_units']==0 and p['admission']['input_tokens_local']<8000
    print('Parameterized execution, independent checker, mandatory refs, forbidden IO, router and fresh-task checks passed')

