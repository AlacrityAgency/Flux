"""Tests 3 & 4: گراف دارای دور رد شود و بیشتر از پنج زیرکار رد شود."""

import pytest
from flux.engine.dag import DAGValidator, DAGValidationError
from flux.contracts.head import SubtaskSpec


def test_dag_cycle_detection_direct():
    """Unit test: Cycle in subtask dependencies raises DAGValidationError."""
    cyclic_subtasks = [
        SubtaskSpec(subtask_id="A", objective="A", assigned_agent="luna", dependencies=["B"]),
        SubtaskSpec(subtask_id="B", objective="B", assigned_agent="luna", dependencies=["A"]),
    ]
    with pytest.raises(DAGValidationError, match="Cycle detected"):
        DAGValidator.validate_and_tier(cyclic_subtasks)


def test_dag_more_than_five_subtasks_direct():
    """Unit test: More than 5 subtasks raises DAGValidationError."""
    many_subtasks = [
        SubtaskSpec(subtask_id=f"sub_{i}", objective=f"Task {i}", assigned_agent="luna", dependencies=[])
        for i in range(1, 7)
    ]
    with pytest.raises(DAGValidationError, match="Maximum 5 subtasks allowed"):
        DAGValidator.validate_and_tier(many_subtasks)


@pytest.mark.asyncio
async def test_engine_rejects_cycle_from_head(engine, fake_provider, sample_task_data):
    """Integration test: Cycle generated by Head Agent causes run to fail safely."""
    fake_provider.scenario = "cycle"

    run_id, _ = engine.submit_run(sample_task_data)
    result = await engine.execute_run(run_id)

    assert result.status == "FAILED"
    assert "DAG" in result.summary or "Cycle" in result.summary
    # No subtasks were executed (only Head ran)
    assert fake_provider.call_count == 1


@pytest.mark.asyncio
async def test_engine_rejects_too_many_subtasks_from_head(engine, fake_provider, sample_task_data):
    """Integration test: More than 5 subtasks from Head Agent causes run to fail."""
    fake_provider.scenario = "too_many_subtasks"

    run_id, _ = engine.submit_run(sample_task_data)
    result = await engine.execute_run(run_id)

    assert result.status == "FAILED"
    assert fake_provider.call_count == 1
